import { readFileSync, mkdirSync, writeFileSync } from "node:fs";

// Reviewable ownership manifest. Globals are explicitly excluded, never guessed.
const globals = new Set(["User", "Session", "LoginThrottle", "Currency", "AgentDefinition"]);
const parents = {
  WorkbookProfile: ["ExcelWorkbook", "workbookId"], MappingVersion: ["MappingTemplate", "templateId"],
  MappingRule: ["MappingVersion", "mappingVersionId"], MappingSuggestion: ["MappingVersion", "mappingVersionId"],
  MappingDecision: ["MappingSuggestion", "suggestionId"], ImportError: ["ImportBatch", "importBatchId"],
  FiscalYear: ["FiscalCalendar", "fiscalCalendarId"], FiscalPeriod: ["FiscalYear", "fiscalYearId"],
  LineageReference: ["FinancialFact", "financialFactId"], CalculationDefinition: ["MetricDefinition", "metricDefinitionId"],
  MetricDependency: ["MetricDefinition", "metricDefinitionId"], PlanVersion: ["Plan", "planId"],
  ForecastVersion: ["Forecast", "forecastId"], ForecastLine: ["ForecastVersion", "forecastVersionId"],
  ForecastComment: ["ForecastVersion", "forecastVersionId"], AccountingJournalLine: ["AccountingJournal", "journalId"],
  WorkflowExecutionRecord: ["WorkflowRunRecord", "runId"], BankTransaction: ["BankAccount", "bankAccountId"],
  ApPaymentAllocation: ["ApPayment", "paymentId"], ArReceiptAllocation: ["ArReceipt", "receiptId"],
  ReportingDisclosureEvidence: ["ReportingRun", "runId"], ReportingApproval: ["ReportingRun", "runId"],
};
const schema = readFileSync("prisma/schema.prisma", "utf8");
const models = [...schema.matchAll(/model (\w+) \{([\s\S]*?)\n\}/g)].map(([, name, body]) => ({ name, body }));
const tenantModels = models.filter(m => !globals.has(m.name));
const tenantNames = new Set(tenantModels.map(m => m.name));
const q = name => `"${name}"`;
const sql = [`-- Generated by scripts/generate-tenant-rls.mjs. No data deletion or role creation.
-- The migration owner has an explicit maintenance policy. Runtime must be a
-- distinct non-owner role with NOINHERIT/NOBYPASSRLS, with no membership in owner.
BEGIN;
CREATE FUNCTION planora_session_tenant() RETURNS uuid
LANGUAGE sql STABLE SECURITY DEFINER
AS $function$
 SELECT m."organizationId" FROM "Session" s
 JOIN "User" u ON u.id=s."userId"
 JOIN "OrganizationMembership" m ON m.id=s."membershipId" AND m."userId"=s."userId"
 JOIN "Organization" o ON o.id=m."organizationId"
 WHERE s."tokenHash"=NULLIF(current_setting('planora.session_hash', true),'')
 AND s."expiresAt">CURRENT_TIMESTAMP AND u.active AND m.active AND o.active
 AND m.role IN ('CFO','FPA_DIRECTOR','ANALYST')
 LIMIT 1
$function$;
-- Bind lookup to the deployment schema, never a caller-controlled search_path.
DO $block$ BEGIN
 EXECUTE format('ALTER FUNCTION planora_session_tenant() SET search_path = %I, pg_catalog', current_schema());
END $block$;
REVOKE ALL ON FUNCTION planora_session_tenant() FROM PUBLIC;
`];
const manifest = [];
for (const { name, body } of tenantModels) {
  let predicate;
  if (name === "Organization") predicate = '"id" = planora_session_tenant()';
  else if (/\n\s+organizationId\s/.test(body)) predicate = '"organizationId" = planora_session_tenant()';
  else {
    const parent = parents[name];
    if (!parent) throw new Error(`Unclassified tenant ownership: ${name}`);
    predicate = `EXISTS (SELECT 1 FROM ${q(parent[0])} p WHERE p.id=${q(name)}.${q(parent[1])})`;
  }
  // Tenant-owned foreign references must also be visible under RLS. This guards
  // INSERT/UPDATE reparenting even when a row has a legitimate organizationId.
  const checks = [];
  for (const match of body.matchAll(/^\s+\w+\s+(\w+)\??\s+@relation\([^\n]*fields:\s*\[(\w+)\],\s*references:\s*\[(\w+)\]/gm)) {
    const [, parent, field, reference] = match;
    if (!tenantNames.has(parent) || parent === name) continue;
    checks.push(`(${q(name)}.${q(field)} IS NULL OR EXISTS (SELECT 1 FROM ${q(parent)} r WHERE r.${q(reference)}=${q(name)}.${q(field)}))`);
  }
  // Parent predicates already recurse down a directed ownership tree. Reference
  // validation is WITH CHECK only, avoiding recursive SELECT policy cycles.
  const withCheck = [predicate, ...checks].map(p => `(${p})`).join(" AND ");
  sql.push(`ALTER TABLE ${q(name)} ENABLE ROW LEVEL SECURITY;
ALTER TABLE ${q(name)} FORCE ROW LEVEL SECURITY;
CREATE POLICY planora_maintenance ON ${q(name)} TO CURRENT_USER USING (true) WITH CHECK (true);
CREATE POLICY planora_tenant ON ${q(name)} USING (${predicate}) WITH CHECK (${withCheck});`);
  manifest.push({ table: name, ownership: parents[name] ?? (name === "Organization" ? "id" : "organizationId"), checkedReferences: checks.length });
}
sql.push("COMMIT;\n");
const directory = "prisma/migrations/20261009060000_tenant_rls";
mkdirSync(directory, { recursive: true });
writeFileSync(`${directory}/migration.sql`, sql.join("\n\n"));
writeFileSync("docs/tenant-rls-manifest.json", JSON.stringify({ tenantTables: manifest, globals: [...globals] }, null, 2)+"\n");
console.log(`Generated forced RLS policies for ${manifest.length} tenant tables.`);
